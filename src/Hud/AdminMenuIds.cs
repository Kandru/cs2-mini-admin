        private static string[] Indexed(string prefix, int count)
        {
            string[] ids = new string[count];
            for (int i = 0; i < count; i++)
            {
                ids[i] = prefix + i;
            }
            return ids;
        }

        private static string[] Fielded(string prefix, string suffix, int count)
        {
            string[] ids = new string[count];
            for (int i = 0; i < count; i++)
            {
                ids[i] = prefix + i + suffix;
            }
            return ids;
        }

        private static string[] Keyed(string prefix, string[] keys, string suffix = "")
        {
            string[] ids = new string[keys.Length];
            for (int i = 0; i < keys.Length; i++)
            {
                ids[i] = prefix + keys[i] + suffix;
            }
            return ids;
        }
